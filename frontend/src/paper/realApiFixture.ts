/** One closed trade shaped like GET /api/paper/real rows (from trade_rows + join_real_rows). */
export function realTradeRow(over: Partial<PaperTradeWithReal> & Pick<PaperTradeWithReal, "slot" | "date" | "entry_time" | "net">): PaperTradeWithReal {
  const entry = over.entry_time;
  const exit = over.exit_time ?? entry + 600;
  const base: PaperTradeWithReal = {
    direction: over.direction ?? "CE",
    side: over.side ?? "LONG",
    signal_time: over.signal_time ?? entry - 60,
    trigger_index: over.trigger_index ?? 25000.35,
    fill_time: entry,
    contract: over.contract ?? "NIFTY 25000 CE 16 NOV 26",
    entry_premium: over.entry_premium ?? 100.5,
    entry_source: over.entry_source ?? "real",
    units: over.units ?? 65,
    rule: over.rule ?? null,
    index_stop: over.index_stop ?? null,
    index_target: over.index_target ?? null,
    premium_stop: over.premium_stop ?? 80.4,
    premium_target: over.premium_target ?? null,
    estimated: over.estimated ?? [],
    exit_time: exit,
    exit_premium: over.exit_premium ?? 110.2,
    exit_reason: over.exit_reason ?? "stop",
    exit_reason_raw: over.exit_reason_raw ?? "stop",
    net: over.net,
    risk: over.risk ?? null,
    r_multiple: over.r_multiple ?? null,
    date: over.date,
    slot: over.slot,
    entry_time: entry,
    index_entry: over.index_entry ?? 25000.35,
    index_exit: over.index_exit ?? null,
    lots: over.lots ?? 1,
    lot_size: over.lot_size ?? 65,
    nifty_points: over.nifty_points ?? null,
    premium_points: over.premium_points ?? 9.7,
    gross: over.gross ?? 630.5,
    charges: over.charges ?? 40.1,
    source: over.source ?? "live",
    index_from_candles: over.index_from_candles ?? [],
    shadow: over.shadow ?? null,
    shadow_net: over.shadow_net ?? over.net ?? 0,
    paper_key: over.paper_key ?? `${over.slot}:${over.date}:${entry}`,
    real: over.real ?? null,
    real_vs_paper: over.real_vs_paper ?? null,
  };
  return { ...base, ...over, paper_key: over.paper_key ?? base.paper_key };
}

